/* Devolucion de la configuración completa del grupo (cuatrimestre, tutor y materias formateadas para MongoDB) */
function obtenerDatosGrupoMongo(string $carrera, string $grupo, array $planes): array {
    $infoGrupo = $planes[$carrera][$grupo] ?? null;
    $materiasFormateadas = [];

    if ($infoGrupo && isset($infoGrupo['materias'])) {
        foreach ($infoGrupo['materias'] as $mat) {
            $materiasFormateadas[] = [
                'clave' => $mat['clave'],
                'nombre' => $mat['nombre'],
                'profesor' => $mat['profesor'],
                'calificaciones' => [
                    'parcial_1' => null,
                    'parcial_2' => null,
                    'parcial_3' => null,
                    'final' => null
                ]
            ];
        }
    }

    return [
        'cuatrimestre' => $infoGrupo['cuatrimestre'] ?? '',
        'tutor' => $infoGrupo['tutor'] ?? '',
        'materias' => $materiasFormateadas
    ];
}